    public boolean fValidateJTableRow(com.gpc.client.common.table.FwoJTableMgr fwoJTableMgr1,
            int row) {
        if (fwoJTableMgr1 == m_TblMgr) {
            int selectedRow = tblCoreBankMaintenance.getSelectedRow();
            Boolean core_status = new Boolean(
                    tblCoreBankMaintenance.getValueAt(selectedRow, 8).toString());
            String reason_text = (String) tblCoreBankMaintenance.getValueAt(selectedRow, 9);
            if (!core_status.booleanValue() && (reason_text == null 
                    || reason_text.trim().equals(TsoConstant.EMPTY_STRING))) {
                taReasonTextArea.setEnabled(false);
            }
            // If check box is selected and reason is entered in text field 
            if (m_TblMgr.haveRowsChanged() && ckbStatusCheckbox.isSelected()) {
                // Do you want to save your changes?
                Boolean bSave = ClientApplicationContext.getClientApplicationContext()
                        .getMessageMgr().showMessageYesNoCancel(this, "120");
                if (bSave == null) { // clicked Cancel
                    taReasonTextArea.setEnabled(true);
                    return false;
                } else if (bSave.booleanValue()) { // clicked Yes
                    if (!FM.fSave()) {
                        return false;
                    }
                } else { // clicked No
                    FM.fCancel();
                }
            }
            populateLineItemDetails();
        }
        return true;
    }

