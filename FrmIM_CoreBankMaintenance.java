    private void handleBillBackCoreActionPerformed() {
    	
    	ClientApplicationContext clientApplicationContext = ClientApplicationContext.getClientApplicationContext();
    	int selectedRow = tblCoreBankMaintenance.getSelectedRow();
        if (selectedRow == -1) {
            return;
        }
        String customerNum = tblCoreBankMaintenance.getValueAt(selectedRow, 0).toString();
        Integer customerNumber = new Integer(customerNum);
        CustomerVO customerVO = null;
        try {
            customerVO = clientApplicationContext.getCustomerDAO().getCustomerDetailInfo(customerNumber);
        } catch (ApplicationException ae) {
            logger.error(ae.toString(), ae);
            clientApplicationContext.getMessageMgr().showMessage(ae.getUserMessageID(),
                    ae.getUserMessageParameters());
            return;
        }
        Integer custId = customerVO.getID();
        Integer loc = new Integer(clientApplicationContext.getLocation());
        String lineAbbr = tblCoreBankMaintenance.getValueAt(selectedRow, 4).toString();
        String partNum = tblCoreBankMaintenance.getValueAt(selectedRow, 5).toString();
        String invoiceNumber = tblCoreBankMaintenance.getValueAt(selectedRow, 2).toString();
        Object poObj = tblCoreBankMaintenance.getValueAt(selectedRow, 10);
        String PO = (poObj != null) ? poObj.toString() : "";
        int quantity = ((Integer) tblCoreBankMaintenance.getValueAt(selectedRow, 7)).intValue();
        generateCoreBillBack(custId,loc,lineAbbr,partNum,invoiceNumber,PO,quantity);
        
	}
    
    private void generateCoreBillBack(Integer custId,Integer loc,String lineAbbr,String partNum,String invoiceNumber,String PO,Integer qty) {
    	Vector vec = new Vector();
    	BaseLineItemVO baseLineItemVO = new BaseLineItemVO();
    	invoiceVO.setLOC(loc);
    	invoiceVO.setCustomerID(custId);
        baseLineItemVO.setLineAbbr(lineAbbr);
        baseLineItemVO.setPartNum(partNum);
    	baseLineItemVO.setDisplayItem(true);
        baseLineItemVO.setQuantityBilled(new BigDecimal(qty));
        baseLineItemVO.setCoreTransaction(true);
        baseLineItemVO.setRequestForCoreBillBack(true);
        invoiceNoteVO = new InvoiceNoteVO();
        invoiceNoteVO.setText("Core bill back from INV # " + invoiceNumber  + " PO # " + PO);
    	
        invoiceNoteVO.setCompletedLine(true);
        invoiceNoteVO.setLineAddedToList(true);
        vec.addElement(baseLineItemVO);
        invoiceVO.setLineItems(vec);
        try {
        	InvoiceLineBL.loadGeneratedLines(invoiceVO); 	
        }
        catch(ApplicationException e) {
        	logger.error("FrmIM_CoreBankMaintenance:generateCoreBillBack()", e);
        }
        
        PointOfSaleEventDispatcher posEventDispather =
                ((ClientApplicationContext) ApplicationContext.getInstance()).getPointOfSaleEventDispatcher();
     
            // Fire invoice loaded
            posEventDispather.fireInvoiceLoaded(new InvoiceEvent(this, invoiceVO, 0, true));
     
            // Dispatch both items in correct order
            SwingUtilities.invokeLater(() -> {
            	javax.swing.Timer timer = new javax.swing.Timer(10, e -> {
                    posEventDispather.fireInvoiceLineItemAdded(
                        new PointOfSaleListEvent(FrmIM_CoreBankMaintenance.this, invoiceNoteVO));
                });
            	timer.setRepeats(false); // Prevent continuous firingtimer.start();
            	timer.start();
            });
    	this.setVisible(false);	
		
    	
    }
    
